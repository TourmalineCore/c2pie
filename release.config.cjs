// Convert custom version identifiers into a format that complies with semver. 
// This conversion may be necessary, for example, so that Poetry can correctly 
// convert the version to PEP 440, the compatible format used by PyPI
function normalizeToSemver(version) {
    const [base, ...rest] = version.split('-');

    if (rest.length === 0)
        return version;

    const identifier = rest.join('-');

    const hotfixMatch = identifier.match(/^hotfix\.(\d+)$/);
    if (hotfixMatch) {
        const [, num] = hotfixMatch;
        return `${base}-rc.${num}`;
    }

    const match = identifier.match(/^\d+x-(alpha|rc|hotfix)\.(\d+)$/);

    if (!match)
        return version;

    const [, phase, num] = match;
    const normalizedPhase = phase === 'hotfix' ? 'rc' : phase;

    return `${base}-${normalizedPhase}.${num}`;
}